function normalizeUiLookup(value: string): string {
  return value
    .replaceAll("&amp;", "&")
    .replaceAll("&apos;", "'")
    .replaceAll("&ldquo;", "“")
    .replaceAll("&rdquo;", "”")
    .replaceAll("&middot;", "·")
    .replaceAll("&rsaquo;", "›")
    .replaceAll("&times;", "×")
    .replaceAll("&lt;", "<")
    .replaceAll("&gt;", ">");
}

const koPatterns: Array<[RegExp, (...args: string[]) => string]> = [
  [/^Loading (.+)\.\.\.$/, (target) => `${translateRawUiText(target, "ko")} 불러오는 중...`],
  [/^Loading (.+)…$/, (target) => `${translateRawUiText(target, "ko")} 불러오는 중…`],
  [/^No (.+) yet\.$/, (target) => `아직 ${translateRawUiText(target, "ko")}이 없습니다.`],
  [/^No (.+) found\.$/, (target) => `${translateRawUiText(target, "ko")}을 찾을 수 없습니다.`],
  [/^No (.+) in this period\.$/, (target) => `이 기간에는 ${translateRawUiText(target, "ko")}이 없습니다.`],
  [/^No (.+) recorded yet\.$/, (target) => `아직 기록된 ${translateRawUiText(target, "ko")}이 없습니다.`],
  [/^Select a company to view (.+)\.$/, (target) => `${translateRawUiText(target, "ko")}을 보려면 회사를 선택하세요.`],
  [/^Select a company to manage (.+)\.$/, (target) => `${translateRawUiText(target, "ko")}을 관리하려면 회사를 선택하세요.`],
  [/^Select a company to create (.+)$/, (target) => `${translateRawUiText(target, "ko")}을 만들려면 회사를 선택하세요.`],
  [/^Back to (.+)$/, (target) => `${translateRawUiText(target, "ko")}로 돌아가기`],
  [/^Create new (.+)$/, (target) => `새 ${translateRawUiText(target, "ko")} 만들기`],
  [/^Add (.+)$/, (target) => `${translateRawUiText(target, "ko")} 추가`],
  [/^View (.+)$/, (target) => `${translateRawUiText(target, "ko")} 보기`],
  [/^Failed to (.+)\.$/, (target) => `${translateRawUiText(target, "ko")}하지 못했습니다.`],
];

export function translateRawUiText(value: string, locale: Locale): string {
  if (locale !== "ko") return value;

  const normalizedValue = normalizeUiLookup(value);
  const exact =
    koSupplementalExactMap[normalizedValue] ??
    koAdditionalExactMap[normalizedValue] ??
    koExactMap[normalizedValue];
  if (exact) return exact;

  for (const [pattern, formatter] of koPatterns) {
    const match = normalizedValue.match(pattern);
    if (match) return formatter(...match.slice(1));
  }

  return normalizedValue;
}
